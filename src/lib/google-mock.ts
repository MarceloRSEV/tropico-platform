export function getMockGoogleDailyData(since: string, until: string) {
  const filtered = DATA.filter(
    r => r.date >= since && r.date <= until
  )

  const dailyMap = new Map<string, { cost: number; impressions: number; clicks: number }>()
  for (const row of filtered) {
    const existing = dailyMap.get(row.date) ?? { cost: 0, impressions: 0, clicks: 0 }
    dailyMap.set(row.date, {
      cost: existing.cost + row.cost,
      impressions: existing.impressions + row.impressions,
      clicks: existing.clicks + row.clicks,
    })
  }

  return Array.from(dailyMap.entries())
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([date, data]) => ({ date, ...data }))
}

export function getMockGoogleCampaignsByType(since: string, until: string) {
  const filtered = DATA.filter(
    r => r.date >= since && r.date <= until
  )

  const typeMap = new Map<string, { cost: number; impressions: number; clicks: number }>()
  for (const row of filtered) {
    const type = row.campaignType === 'Pesquisa' ? 'Tráfego' : 'Vendas'
    const existing = typeMap.get(type) ?? { cost: 0, impressions: 0, clicks: 0 }
    typeMap.set(type, {
      cost: existing.cost + row.cost,
      impressions: existing.impressions + row.impressions,
      clicks: existing.clicks + row.clicks,
    })
  }

  return Array.from(typeMap.entries()).map(([type, data]) => ({ type, ...data }))
}
